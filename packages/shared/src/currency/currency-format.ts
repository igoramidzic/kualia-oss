// Default format for unknown currencies
const DEFAULT_FORMAT: CurrencyFormat = {
  symbol: '',
  symbolPosition: 'before',
  decimalSeparator: '.',
  thousandSeparator: ',',
  decimalPlaces: 2,
};

/**
 * Get currency format configuration
 */
export function getCurrencyFormat(currencyCode: string): CurrencyFormat {
  return (
    CURRENCY_FORMATS[currencyCode.toUpperCase()] ?? {
      ...DEFAULT_FORMAT,
      symbol: currencyCode.toUpperCase(),
      spaceBetweenSymbolAndValue: true,
    }
  );
}

/**
 * Format a number as currency (display units - e.g., dollars, not cents)
 */
export function formatCurrencyDisplay(
  amount: number,
  currencyCode = 'USD',
  options?: {
    showSign?: boolean;
    hideSymbol?: boolean;
  }
): string {
  const format = getCurrencyFormat(currencyCode);
  const isNegative = amount < 0;
  const absoluteAmount = Math.abs(amount);

  // Handle decimal places
  const factor = Math.pow(10, format.decimalPlaces);
  const rounded = Math.round(absoluteAmount * factor) / factor;

  // Split into integer and decimal parts
  const [integerPart, decimalPart = ''] = rounded.toFixed(format.decimalPlaces).split('.');

  // Add thousand separators
  const formattedInteger = integerPart.replace(/\B(?=(\d{3})+(?!\d))/g, format.thousandSeparator);

  // Combine integer and decimal parts
  let formattedAmount = formattedInteger;
  if (format.decimalPlaces > 0 && decimalPart) {
    formattedAmount += format.decimalSeparator + decimalPart;
  }

  // Add currency symbol
  if (!options?.hideSymbol) {
    const space = format.spaceBetweenSymbolAndValue ? ' ' : '';
    if (format.symbolPosition === 'before') {
      formattedAmount = format.symbol + space + formattedAmount;
    } else {
      formattedAmount = formattedAmount + space + format.symbol;
    }
  }

  // Add sign
  if (isNegative || options?.showSign) {
    const sign = isNegative ? '-' : '+';
    formattedAmount = sign + formattedAmount;
  }

  return formattedAmount;
}

/**
 * Parse a currency string to a number
 */
export function parseCurrency(value: string, currencyCode = 'USD'): number | null {
  if (!value || typeof value !== 'string') return null;

  const format = getCurrencyFormat(currencyCode);

  // Remove currency symbol and spaces
  let cleaned = value.replace(new RegExp(`\\${format.symbol}`, 'g'), '').trim();

  // Remove thousand separators
  cleaned = cleaned.replace(new RegExp(`\\${format.thousandSeparator}`, 'g'), '');

  // Replace decimal separator with dot
  cleaned = cleaned.replace(format.decimalSeparator, '.');

  // Remove any remaining non-numeric characters except dot and minus
  cleaned = cleaned.replace(/[^0-9.-]/g, '');

  const parsed = parseFloat(cleaned);
  return isNaN(parsed) ? null : parsed;
}
